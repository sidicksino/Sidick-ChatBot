"""Pull the project list from the portfolio's admin API into knowledge/projects.md.

Run:  python ingest_portfolio.py

The portfolio site and this bot now read the same source: the projects you edit in the dashboard
(https://www.sidickabdoulaye.com/admin). Re-run this after changing projects there, then restart the bot.
Before this existed the bot had its own hand-copied list, which went stale (old descriptions, and it
recommended the mobile apps first because they were what it knew best).

Render's free tier sleeps, so the first request can take up to a minute; this retries.
If the API can't be reached, the existing knowledge/projects.md is kept unchanged.
"""
import os
import sys
import time
from pathlib import Path

import requests
from dotenv import load_dotenv

ROOT = Path(__file__).parent
load_dotenv(ROOT / ".env")
API = os.getenv("PORTFOLIO_API", "https://sidickportfolio.onrender.com").rstrip("/")
SITE = os.getenv("PORTFOLIO_URL", "https://www.sidickabdoulaye.com").rstrip("/")
OUT = ROOT / "knowledge" / "projects.md"

# Category id in the dashboard -> (section prefix chatbot.py looks for, plural label for lists).
# The prefixes must match _PROJECT_HEADING and _CATEGORIES in chatbot.py.
CATEGORIES = {
    "web": ("Web project", "web projects"),
    "mobile": ("Mobile app", "mobile apps"),
    "ai": ("ML & AI project", "ML & AI projects"),
    "design": ("Design project", "design projects"),
}


def fetch(attempts=5):
    for i in range(1, attempts + 1):
        try:
            r = requests.get(f"{API}/projects", timeout=60)
            r.raise_for_status()
            data = r.json()
            if isinstance(data, list) and data:
                return data
            raise ValueError("API returned no projects")
        except (requests.RequestException, ValueError) as e:
            print(f"  attempt {i}/{attempts} failed: {e}", flush=True)
            time.sleep(min(10 * i, 30))
    return None


def section(p):
    prefix, _ = CATEGORIES.get(p["category"], ("Project", "projects"))
    name = p.get("title_en") or p.get("title_fr")
    description = (p.get("description_en") or "").strip()
    if p["category"] == "design":
        description += " A UI/UX design made in Figma."
    lines = [f"## {prefix}: {name}", description]
    if p.get("description_fr"):
        lines.append(f"En français : {p['description_fr'].strip()}")
    tech = [t for t in p.get("technologies") or [] if t.lower() != "github"]
    if tech:
        lines.append(f"Tech: {', '.join(tech)}.")
    links = []
    if p.get("live_url"):
        links.append(("Figma design" if "figma.com" in p["live_url"] else "Live") + f": {p['live_url']}")
    if p.get("github_url"):
        links.append(f"Code: {p['github_url']}")
    if links:
        lines.append(" — ".join(links))
    if p.get("featured"):
        lines.append("One of the featured projects on my portfolio.")
    return "\n".join(line for line in lines if line)


def build(projects):
    projects = sorted(projects, key=lambda p: (p.get("sort_order") or 0, p.get("id") or 0))
    featured = sorted((p for p in projects if p.get("featured")), key=lambda p: p.get("featured_order") or 99)
    by_cat = {c: [p for p in projects if p["category"] == c] for c in CATEGORIES}
    title = lambda p: p.get("title_en") or p.get("title_fr")  # noqa: E731

    counts = ", ".join(f"{len(by_cat[c])} {CATEGORIES[c][1]}" for c in CATEGORIES if by_cat[c])
    out = [
        "# My projects (generated by ingest_portfolio.py from the portfolio dashboard: do not edit by hand)",
        "",
        "## Portfolio: overview of my projects",
        f"My portfolio ({SITE}/#work) lists {len(projects)} projects: {counts}.",
        f"My featured work, the projects I show first: {', '.join(title(p) for p in featured)}.",
        "En français : mes projets principaux sont " + ", ".join(title(p) for p in featured) + ".",
    ]
    for c, (prefix, label) in CATEGORIES.items():
        if by_cat[c]:
            out += ["", f"## Portfolio: list of my {label}",
                    f"My {len(by_cat[c])} {label}{' (UI/UX designs made in Figma)' if c == 'design' else ''}: "
                    f"{', '.join(title(p) for p in by_cat[c])}."]
    # One place with every link, for "give me the links" / "donne-moi les liens".
    out += ["", "## Portfolio: links to my projects (live sites and code)",
            "Links to see my projects (liens vers mes projets) — the featured ones first:"]
    for p in featured + [p for p in projects if not p.get("featured") and p["category"] != "design"]:
        links = [u for u in (p.get("live_url"), p.get("github_url")) if u]
        if links:
            out.append(f"- {title(p)}: {' | '.join(links)}")
    out.append(f"All projects, with screenshots: {SITE}/#work")
    for p in featured + [p for p in projects if not p.get("featured")]:
        out += ["", section(p)]
    return "\n".join(out) + "\n"


def main():
    projects = fetch()
    if projects is None:
        print(f"Could not reach {API}; kept the existing {OUT.name}.")
        return 1
    OUT.write_text(build(projects), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(projects)} projects.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
